#!/usr/bin/env node
/**
 * Regenerates lib/i18n/messages/index.ts from the per-namespace catalogue
 * files, so that adding a namespace is adding ONE file — no shared file to
 * edit, no merge conflict between two bands landing at once.
 *
 *   lib/i18n/messages/en/<Namespace>.json   the source strings of one namespace
 *   lib/i18n/messages/fr/<Namespace>.json   its (partial) French seed
 *
 * Usage:
 *   node scripts/i18n/build-messages-index.mjs          rewrite the index
 *   node scripts/i18n/build-messages-index.mjs --check  exit 1 if it is stale
 *
 * Deterministic: namespaces are sorted, so concurrent runs converge on the
 * same file. A namespace file name must be a PascalCase identifier — it
 * becomes the top-level key every `t()` call addresses.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const MESSAGES_DIR = path.join(ROOT, "lib", "i18n", "messages");
const INDEX_FILE = path.join(MESSAGES_DIR, "index.ts");
const LOCALES = ["en", "fr"];
const NAMESPACE = /^[A-Z][A-Za-z0-9]*$/;

export function listNamespaces(locale) {
  const dir = path.join(MESSAGES_DIR, locale);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .map((name) => name.slice(0, -".json".length))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

export function renderIndex() {
  const byLocale = Object.fromEntries(LOCALES.map((locale) => [locale, listNamespaces(locale)]));
  const problems = [];
  for (const locale of LOCALES) {
    for (const ns of byLocale[locale]) {
      if (!NAMESPACE.test(ns)) problems.push(`${locale}/${ns}.json: not a PascalCase namespace name`);
      if (locale !== "en" && !byLocale.en.includes(ns)) {
        problems.push(`${locale}/${ns}.json: no en/${ns}.json — the source catalogue defines the namespaces`);
      }
      try {
        JSON.parse(readFileSync(path.join(MESSAGES_DIR, locale, `${ns}.json`), "utf8"));
      } catch (error) {
        problems.push(`${locale}/${ns}.json: ${error instanceof Error ? error.message : String(error)}`);
      }
    }
  }
  if (problems.length) throw new Error(problems.join("\n"));

  const lines = [
    "/* GENERATED by scripts/i18n/build-messages-index.mjs — do not edit by hand.",
    " * Add lib/i18n/messages/<locale>/<Namespace>.json and run `npm run i18n:index`. */",
    "",
  ];
  for (const locale of LOCALES) {
    for (const ns of byLocale[locale]) lines.push(`import ${locale}_${ns} from "./${locale}/${ns}.json";`);
  }
  lines.push("");
  for (const locale of LOCALES) {
    lines.push(`export const ${locale} = {`);
    for (const ns of byLocale[locale]) lines.push(`  ${ns}: ${locale}_${ns},`);
    lines.push("};", "");
  }
  return lines.join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const next = renderIndex();
  const current = existsSync(INDEX_FILE) ? readFileSync(INDEX_FILE, "utf8") : null;
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("lib/i18n/messages/index.ts is stale — run `npm run i18n:index` and commit the result.");
      process.exit(1);
    }
    console.log("lib/i18n/messages/index.ts is up to date.");
  } else if (current !== next) {
    writeFileSync(INDEX_FILE, next);
    console.log("wrote lib/i18n/messages/index.ts");
  } else {
    console.log("lib/i18n/messages/index.ts unchanged");
  }
}
